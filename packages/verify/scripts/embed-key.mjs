// Compiles keys/login_vk.json into src/login-vk.ts, so that the key travels
// inside the JavaScript module graph: no file system, createRequire or JSON
// import is needed to load it, and no bundler can leave it out. Runs before
// every build; writes only when the key changed. A test keeps both identical.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const key = JSON.parse(readFileSync(join(root, "keys", "login_vk.json"), "utf8"));
const target = join(root, "src", "login-vk.ts");
const source = `// Generated by scripts/embed-key.mjs from keys/login_vk.json. Do not edit.

/** The login verifying key, compiled into the module so every runtime and bundler ships it. */
export const LOGIN_VERIFICATION_KEY: object = ${JSON.stringify(key, null, 2)};
`;
let current = "";
try { current = readFileSync(target, "utf8").replaceAll("\r\n", "\n"); } catch { /* first run */ }
if (current !== source) {
  writeFileSync(target, source);
  console.log("Embedded keys/login_vk.json into src/login-vk.ts");
}
