#!/usr/bin/env bash
# Verifies a ceremony from its files and writes <dir>/TRANSCRIPT.md.
#
#   scripts/ceremony/verify.sh <ceremony-dir> <min-contributions> [final]
#
# It trusts nothing in <dir> that it can check:
#  - the Powers of Tau must match the BLAKE2b digest snarkjs publishes;
#  - the circuits are recompiled from this checkout with the manifest's
#    circom version and must match the manifest's r1cs hashes;
#  - `snarkjs zkey verify` re-derives each key from that r1cs and the Powers
#    of Tau and checks every contribution in order;
#  - every contribution must match a contributor's attestation (number,
#    name and hash) and every attestation must appear in the chain, so a
#    dropped, reordered or substituted contribution is refused;
#  - both circuits carry the same contributions, at least <min> of them.
# Without "final" it checks the latest numbered keys of an open ceremony
# and rewrites TRANSCRIPT.md. With "final" it checks the sealed keys, which
# must end in one beacon contribution made from the beacon in beacon.txt,
# and an existing TRANSCRIPT.md must equal the regenerated one byte for
# byte: a published transcript that misstates the ceremony is refused.
source "$(dirname "$0")/common.sh"

usage="usage: verify.sh <ceremony-dir> <min-contributions> [final]"
DIR="${1:?$usage}"
MIN="${2:?$usage}"
MODE="${3:-open}"
[[ "$MIN" =~ ^[1-9][0-9]*$ ]] || die "min-contributions must be a positive number"
case "$MODE" in open | final) ;; *) die "$usage" ;; esac
M="$DIR/manifest.json"
[ -f "$M" ] || die "$M missing"
if [ "$MODE" = open ] && sealed "$DIR"; then
  die "this ceremony is sealed; verify it with: verify.sh $DIR $MIN final"
fi

COMMIT="$(json_get "$M" commit)"
CIRCOM="$(json_get "$M" circom)"
[ "$(json_get "$M" ptau.blake2b)" = "$PTAU_B2SUM" ] || die "the manifest names a different Powers of Tau"
require_circom "$CIRCOM"
fetch_ptau "$DIR"
if [ "$(git -C "$REPO_ROOT" rev-parse HEAD 2>/dev/null || true)" != "$COMMIT" ]; then
  echo "note: this checkout is not the ceremony commit $COMMIT; its circuits must still compile to the same r1cs" >&2
fi
if [ "$MODE" = final ]; then
  [ -f "$DIR/beacon.txt" ] || die "$DIR/beacon.txt missing"
  BEACON="$(tr -d ' \r\n' < "$DIR/beacon.txt")"
  [[ "$BEACON" =~ ^[0-9a-f]{64}$ ]] || die "$DIR/beacon.txt must hold 64 lowercase hex characters"
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# Attested contributions, one "<circuit> <number> <hash> <name>" per line.
for f in "$DIR"/attestations/*.txt; do
  [ -e "$f" ] || continue
  awk '
    { sub(/\r$/, "") }
    /^contributor: / { name = substr($0, 14) }
    $1 == "contribution" && NF == 4 { print $2 "\t" $3 "\t" $4 "\t" name }
  ' "$f"
done | LC_ALL=C sort > "$WORK/attested.tsv"

T="$WORK/TRANSCRIPT.md"
{
  echo "# GhostLink phase-2 ceremony transcript"
  echo
  echo "Generated by \`scripts/ceremony/verify.sh\` from the ceremony files. Running it again on the same files reproduces this file byte for byte."
  echo
  if [ "$MODE" = final ]; then
    echo "- Status: sealed with a public random beacon"
  else
    echo "- Status: open, contributions are still being collected"
  fi
  echo "- Circuits: commit \`$COMMIT\`, circom $CIRCOM, snarkjs $(json_get "$M" snarkjs)"
  echo "- Phase 1: \`$PTAU_FILE\`, BLAKE2b \`$PTAU_B2SUM\`"
  if [ "$MODE" = final ]; then
    echo "- Beacon: \`$BEACON\`, hashed 2^$BEACON_ITERATIONS_EXP times"
  fi
} > "$T"

count=""
: > "$WORK/chain.tsv"
for c in "${CIRCUITS[@]}"; do
  echo "== $c: recompiling from this checkout =="
  compile_circuit "$c" "$WORK/$c"
  r1cs="$(sha256_of "$WORK/$c/$c.r1cs")"
  [ "$r1cs" = "$(json_get "$M" "circuits.$c.r1cs_sha256")" ] \
    || die "$c: this checkout compiles to r1cs $r1cs, not the manifest's; check out $COMMIT"
  if [ -f "$DIR/$c/$c.r1cs" ] && [ "$(sha256_of "$DIR/$c/$c.r1cs")" != "$r1cs" ]; then
    die "$c: $DIR/$c/$c.r1cs differs from the manifest"
  fi

  if [ "$MODE" = final ]; then
    key="$DIR/$c/${c}_final.zkey"
  else
    idx="$(latest_index "$DIR" "$c")"
    [ -n "$idx" ] || die "no key for $c in $DIR"
    key="$DIR/$c/${c}_$idx.zkey"
  fi
  [ -f "$key" ] || die "missing $key"
  echo "== $c: verifying every contribution in $(basename "$key") =="
  if ! out="$(snarkjs zkey verify "$WORK/$c/$c.r1cs" "$DIR/$PTAU_FILE" "$key" 2>&1)" || [[ "$out" != *"ZKey Ok!"* ]]; then
    printf '%s\n' "$out" | sed -E 's/\x1b\[[0-9;]*m//g' | grep -E "INVALID|ERROR|Error" | strip_log >&2 || true
    die "$c: $(basename "$key") does not verify against the r1cs and the Powers of Tau"
  fi
  printf '%s\n' "$out" | parse_chain > "$WORK/$c.chain"
  cshash="$(printf '%s\n' "$out" | hash_after "Circuit Hash:")"

  # A sealed key ends in exactly one beacon contribution; an open one has none.
  total="$(wc -l < "$WORK/$c.chain")"
  beacons="$(awk -F'\t' '$3 != "-"' "$WORK/$c.chain" | wc -l)"
  if [ "$MODE" = final ]; then
    [ "$beacons" -eq 1 ] || die "$c: expected one beacon contribution, found $beacons"
    IFS=$'\t' read -r _ _ beacon iters _ < <(tail -n 1 "$WORK/$c.chain")
    [ "$beacon" = "$BEACON" ] || die "$c: the last contribution is not the beacon in beacon.txt"
    [ "$iters" = "$BEACON_ITERATIONS_EXP" ] || die "$c: the beacon was not hashed 2^$BEACON_ITERATIONS_EXP times"
    n=$((total - 1))
  else
    [ "$beacons" -eq 0 ] || die "$c: an open ceremony must not contain a beacon contribution"
    n="$total"
  fi
  [ "$n" -ge "$MIN" ] || die "$c: $n contributions, fewer than the required $MIN"
  [ -z "$count" ] || [ "$count" -eq "$n" ] || die "$c has $n contributions, ${CIRCUITS[0]} has $count"
  count="$n"
  awk -F'\t' -v c="$c" -v n="$n" '$1 <= n { print c "\t" $1 "\t" $2 "\t" $5 }' "$WORK/$c.chain" >> "$WORK/chain.tsv"

  {
    echo
    echo "## $c"
    echo
    echo "- r1cs SHA-256: \`$r1cs\`"
    echo "- Circuit hash: \`$cshash\`"
    echo "- Proving key \`$(basename "$key")\` SHA-256: \`$(sha256_of "$key")\`"
  } >> "$T"
  if [ "$MODE" = final ]; then
    # The verifying key the repository installs must come from this key.
    vk="$DIR/final/${c}_vk.json"
    [ -f "$vk" ] || die "missing $vk"
    snarkjs zkey export verificationkey "$key" "$WORK/${c}_vk.json" >/dev/null
    node -e '
      const fs = require("fs");
      const canon = (v) => Array.isArray(v) ? v.map(canon) : v && typeof v === "object"
        ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, canon(v[k])])) : v;
      const [a, b] = process.argv.slice(1).map((f) => JSON.stringify(canon(JSON.parse(fs.readFileSync(f, "utf8")))));
      process.exit(a === b ? 0 : 1);
    ' "$vk" "$WORK/${c}_vk.json" || die "$c: $vk is not the verifying key of $(basename "$key")"
    echo "- Verifying key \`final/${c}_vk.json\` SHA-256: \`$(sha256_of "$vk")\`" >> "$T"
  fi
  {
    echo
    echo "| # | Contributor | Contribution hash |"
    echo "| ---: | --- | --- |"
    awk -F'\t' '{ printf "| %d | %s | `%s` |\n", $1, ($3 == "-" ? $5 : "Random beacon"), $2 }' "$WORK/$c.chain"
  } >> "$T"
  echo "$c: valid, $n contributions"
done

# Every contribution must be attested, and every attestation in the chain.
LC_ALL=C sort "$WORK/chain.tsv" > "$WORK/chain.sorted"
if ! cmp -s "$WORK/chain.sorted" "$WORK/attested.tsv"; then
  LC_ALL=C comm -23 "$WORK/chain.sorted" "$WORK/attested.tsv" | sed 's/^/in the chain but not attested: /' >&2
  LC_ALL=C comm -13 "$WORK/chain.sorted" "$WORK/attested.tsv" | sed 's/^/attested but not in the chain: /' >&2
  die "the contributions do not match the attestations in $DIR/attestations"
fi

if [ "$MODE" = final ] && [ -f "$DIR/TRANSCRIPT.md" ]; then
  if ! cmp -s "$T" "$DIR/TRANSCRIPT.md"; then
    diff "$DIR/TRANSCRIPT.md" "$T" >&2 || true
    die "$DIR/TRANSCRIPT.md does not match the verified ceremony (lines marked > are what it should say)"
  fi
else
  cp "$T" "$DIR/TRANSCRIPT.md"
fi
echo "verified: $count attested contributions per circuit; transcript: $DIR/TRANSCRIPT.md"
